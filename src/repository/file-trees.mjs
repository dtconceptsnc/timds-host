// Large trees cross native RPC as references; only one bounded file is materialized.
// No storage credentials or general-purpose object proxy enter a source container.
const encoder=new TextEncoder();
export const FILE_TREE_KIND='timds-file-tree';
const uuid=/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i;
const hash=/^[a-f0-9]{64}$/;
const fail=message=>Object.assign(new Error(message),{statusCode:409});
export const isFileTree=value=>value?.kind===FILE_TREE_KIND;
export function safeTreePath(value){
 if(typeof value!=='string'||!value||value.length>1000||/[\\\x00-\x1f\x7f]/.test(value)||value.startsWith('/')||value.split('/').some(p=>!p||p==='.'||p==='..'||p.toLowerCase()==='.git'))throw fail('Invalid snapshot path');
 return value;
}
export async function sha256(value){return [...new Uint8Array(await crypto.subtle.digest('SHA-256',value))].map(x=>x.toString(16).padStart(2,'0')).join('');}
export function validateTreeManifest(manifest,{maxFiles=4000,maxBytes=50*1024*1024,maxFileBytes=10*1024*1024}={}){
 if(manifest?.version!==1||!Array.isArray(manifest.files)||manifest.files.length>maxFiles)throw fail('Invalid snapshot manifest');
 const seen=new Set();let total=0;
 for(const file of manifest.files){safeTreePath(file.path);if(seen.has(file.path)||!hash.test(file.sha256||'')||!Number.isSafeInteger(file.size)||file.size<0||file.size>maxFileBytes||!['100644','100755','120000'].includes(file.mode))throw fail('Invalid snapshot entry');seen.add(file.path);total+=file.size;}
 if(total>maxBytes||manifest.totalBytes!==total)throw fail('Invalid snapshot size');
 return manifest;
}
const outputLimits={maxFiles:10000,maxBytes:100*1024*1024,maxFileBytes:12_000_000};
function identity(sourceId,operationId,role){if(!uuid.test(sourceId)||!uuid.test(operationId)||!/^[a-zA-Z][a-zA-Z0-9-]{0,79}$/.test(role))throw fail('Invalid snapshot identity');return `snapshots/${sourceId}/${operationId}/${role}`;}
async function putOnce(bucket,key,body,options={}){
 const existing=await bucket.head(key);
 if(existing){if(options.customMetadata?.sha256&&existing.customMetadata?.sha256!==options.customMetadata.sha256)throw fail('Immutable snapshot collision');return;}
 await bucket.put(key,body,{...options,onlyIf:{etagDoesNotMatch:'*'}});
}
/** descriptor is generated by image-baked code; readFile never accepts an external URL. */
export async function persistContainerTree(bucket,{sourceId,operationId,role,manifest,readFile,artifact=false,deadline=Infinity}){
 validateTreeManifest(manifest,artifact?outputLimits:undefined);
 const digest=await sha256(encoder.encode(JSON.stringify(manifest))),prefix=`${identity(sourceId,operationId,role)}/${digest}`;
 for(let i=0;i<manifest.files.length;i++){
  if(Date.now()>deadline)throw fail('Snapshot transfer deadline exceeded');
  const file=manifest.files[i],key=`${prefix}/blobs/${file.sha256}`;
  const prior=await bucket.head(key);if(prior){if(prior.size!==file.size||prior.customMetadata?.sha256!==file.sha256)throw fail('Immutable snapshot collision');continue;}
  const response=await readFile(i);
  if(!response.ok)throw fail('Snapshot file unavailable');
  let bytes=0;const transfer=typeof FixedLengthStream==='function'?new FixedLengthStream(file.size):new TransformStream({transform(chunk,controller){bytes+=chunk.byteLength;if(bytes>file.size)throw fail('Snapshot byte count changed');controller.enqueue(chunk);},flush(){if(bytes!==file.size)throw fail('Snapshot byte count changed');}});const stream=response.body?.pipeThrough(transfer);
  await putOnce(bucket,key,stream||new Uint8Array(),{sha256:file.sha256,customMetadata:{sha256:file.sha256},httpMetadata:{contentType:'application/octet-stream'}});
 }
 const ref=`${prefix}/manifest.json`;
 await putOnce(bucket,ref,JSON.stringify(manifest),{customMetadata:{sha256:digest},httpMetadata:{contentType:'application/json'}});
 return {kind:FILE_TREE_KIND,ref,digest,entryCount:manifest.files.length,totalBytes:manifest.totalBytes,...(artifact?{artifact:true}:{})};
}
export async function readTreeManifest(bucket,tree){
 if(!isFileTree(tree)||!/^snapshots\/[a-f0-9-]{36}\/[a-f0-9-]{36}\/[a-zA-Z][a-zA-Z0-9-]{0,79}\/[a-f0-9]{64}\/manifest\.json$/.test(tree.ref||'')||!hash.test(tree.digest||''))throw fail('Invalid snapshot reference');
 const object=await bucket.get(tree.ref);if(!object||object.size>2*1024*1024)throw fail('Snapshot manifest unavailable');
 const text=await object.text();if(await sha256(encoder.encode(text))!==tree.digest)throw fail('Snapshot manifest identity changed');
 const manifest=validateTreeManifest(JSON.parse(text),tree.artifact?outputLimits:undefined);
 if(manifest.files.length!==tree.entryCount||manifest.totalBytes!==tree.totalBytes)throw fail('Snapshot reference identity changed');
 return manifest;
}
export async function readTreeFile(bucket,tree,file){
 const key=tree.ref.replace(/manifest\.json$/,`blobs/${file.sha256}`),object=await bucket.get(key);
 if(!object||object.size!==file.size||object.customMetadata?.sha256!==file.sha256)throw fail('Snapshot file unavailable');
 return object;
}
export async function* treeFiles(bucket,tree,{filter=()=>true}={}){
 const manifest=await readTreeManifest(bucket,tree);
 for(const file of manifest.files){if(!filter(file))continue;const object=await readTreeFile(bucket,tree,file);const bytes=new Uint8Array(await object.arrayBuffer());if(await sha256(bytes)!==file.sha256)throw fail('Snapshot file identity changed');yield {path:file.path,mode:file.mode,encoding:'base64',content:Buffer.from(bytes).toString('base64')};}
}
async function* jsonTree(bucket,tree){
 const manifest=await readTreeManifest(bucket,tree);yield '[';let first=true;
 for(const file of manifest.files){
  if(!first)yield ',';first=false;yield `{"path":${JSON.stringify(file.path)},"mode":${JSON.stringify(file.mode)},"encoding":"base64","content":"`;
  const object=await readTreeFile(bucket,tree,file),reader=object.body.getReader();let carry=new Uint8Array();
  try{while(true){const {done,value}=await reader.read();if(done)break;const chunk=new Uint8Array(carry.length+value.length);chunk.set(carry);chunk.set(value,carry.length);const end=chunk.length-chunk.length%3;if(end)yield Buffer.from(chunk.subarray(0,end)).toString('base64');carry=chunk.slice(end);}if(carry.length)yield Buffer.from(carry).toString('base64');}finally{await reader.cancel();}
  yield '"}';
 }
 yield ']';
}
async function* jsonValue(value,bucket){
 if(isFileTree(value)){yield* jsonTree(bucket,value);return;}
 if(Array.isArray(value)){yield '[';for(let i=0;i<value.length;i++){if(i)yield ',';yield* jsonValue(value[i]??null,bucket);}yield ']';return;}
 if(value&&typeof value==='object'){yield '{';let first=true;for(const [key,entry] of Object.entries(value)){if(entry===undefined)continue;if(!first)yield ',';first=false;yield `${JSON.stringify(key)}:`;yield* jsonValue(entry,bucket);}yield '}';return;}
 yield JSON.stringify(value)??'null';
}
/** Public v1 JSON stays byte-compatible, but a 50 MiB tree never enters Worker heap. */
export function streamJsonFileTrees(result,bucket,{status=200,headers={}}={}){
 const iterator=jsonValue(result,bucket)[Symbol.asyncIterator]();
 return new Response(new ReadableStream({async pull(controller){try{const item=await iterator.next();if(item.done)controller.close();else controller.enqueue(encoder.encode(item.value));}catch(error){controller.error(error);}},async cancel(){await iterator.return?.();}}),{status,headers:{'Content-Type':'application/json; charset=utf-8',...headers}});
}
